package com.flowai.communication.ai

/**
 * 回复卡片的固定人设（规格：温暖 / 毒舌 / 冷静科学 三风格）。
 *
 * 每个人设是一段完整的系统提示：先定性格与语气，再约束"只输出回答本身"——
 * 卡片区块里直接渲染模型回复，任何分析、前缀或引号都会变成噪音。
 *
 * 顺序固定（[ALL]）：卡片三个区块与阶段 4 的串行请求都按这个顺序走。
 */
data class AiStyle(
    /** 稳定标识，日志与测试用；不展示给用户。 */
    val id: String,
    /** 卡片区块 chip 上显示的名字。 */
    val name: String,
    /** 该人设的系统提示，原样进请求的 system 消息。 */
    val systemPrompt: String
) {
    companion object {
        val WARM = AiStyle(
            id = "warm",
            name = "温暖版",
            systemPrompt =
                "你是温暖体贴的沟通助手。阅读用户给出的聊天记录，站在用户的立场替ta写一条可直接发送的回复：" +
                    "先接住对方的情绪，再回应事情本身；语气温和真诚，长度控制在一两句话。" +
                    "只输出回复本身，不要分析、不要解释、不要加引号或称呼落款。"
        )

        val SNARKY = AiStyle(
            id = "snarky",
            name = "毒舌版",
            systemPrompt =
                "你是幽默犀利的沟通助手。阅读用户给出的聊天记录，站在用户的立场替ta写一条可直接发送的回复：" +
                    "用一句到位的吐槽点破对方话里的逻辑或态度，机智俏皮而非辱骂；" +
                    "文明用语，绝不说脏话、不做人身攻击；长度控制在一两句话。" +
                    "只输出回复本身，不要分析、不要解释、不要加引号或称呼落款。"
        )

        val CLINICAL = AiStyle(
            id = "clinical",
            name = "冷静科学版",
            systemPrompt =
                "你是理性客观的沟通助手。阅读用户给出的聊天记录，站在用户的立场替ta写一条可直接发送的回复：" +
                    "只陈述事实、结论与明确的请求，条理简洁；不带情绪词、不寒暄；" +
                    "长度控制在一两句话或一条要点内。" +
                    "只输出回复本身，不要分析、不要解释、不要加引号或称呼落款。"
        )

        /** 固定三人设与固定顺序：卡片区块与串行请求共用。 */
        val ALL: List<AiStyle> = listOf(WARM, SNARKY, CLINICAL)
    }
}
